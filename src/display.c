void displayClear(void){
    memset(oled_buffer, 0, sizeof(oled_buffer));
}

void displayInit(void) {
    i2c_master_bus_config_t bus_config = {
        .i2c_port = I2C_MASTER_NUM,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_new_master_bus(&bus_config, &bus_handle);

    i2c_device_config_t dev_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = SSD1306_I2C_ADDRESS,
        .scl_speed_hz = I2C_MASTER_FREQ_HZ,
    };
    i2c_master_bus_add_device(bus_handle, &dev_config, &dev_handle);

    uint8_t init_cmds[] = {
        0x00, 
        0xAE,             // Display OFF
        0xD5, 0x80,       // Set display clock divide ratio/oscillator frequency
        0xA8, 0x3F,       // Set multiplex ratio (1-64) -> 0x3F para 64 linhas
        0xD3, 0x00,       // Set display offset
        0x40,             // Set start line address
        0x8D, 0x14,       // Charge pump setting (0x14 enable charge pump)
        0x20, 0x00,       // Memory addressing mode (0x00 horizontal)
        0xA1,             // Set segment re-map ( columnas invertidas se necessário: A0/A1)
        0xC8,             // Set com output scan direction
        0xDA, 0x12,       // Set com pins hardware configuration -> 0x12 para altura 64
        0x81, 0xCF,       // Set contrast control register
        0xD9, 0xF1,       // Set pre-charge period
        0xDB, 0x40,       // Set vcomh deselect level
        0xA4,             // Disable entire display on (0xA4 resume)
        0xA6,             // Set normal display (0xA6 normal, 0xA7 inverse)
        0xAF              // Display ON
    };
    i2c_master_transmit(dev_handle, init_cmds, sizeof(init_cmds), 1000);
}

void displayDrawString(int x, int y, const char *str){
    if (str == NULL || x >= OLED_WIDTH || y >= OLED_HEIGHT) {
        return;
    }

    int current_x = x;
    const uint8_t *p = (const uint8_t*)str;

    while (*p) {
        uint32_t codepoint = 0;
        int bytes_read = 1;

        if (*p < 0x80) {
            codepoint = *p;
            bytes_read = 1;
        } 
        else if ((*p & 0xE0) == 0xC0 && (*(p + 1) & 0xC0) == 0x80) {
            codepoint = ((*p & 0x1F) << 6) | (*(p + 1) & 0x3F);
            bytes_read = 2;
        } 
        else {
            codepoint = *p;
            bytes_read = 1;
        }

        if (current_x + 8 > OLED_WIDTH) {
            break;
        }

        const uint8_t *glyph = get_font_glyph(codepoint);
        int page = y / 8;
        int bit_shift = y % 8;

        for (int col = 0; col < 8; col++) {
            uint8_t glyph_col = glyph[col];

            if (page < (OLED_HEIGHT / 8)) {
                int buf_index = page * OLED_WIDTH + (current_x + col);
                oled_buffer[buf_index] |= (glyph_col << bit_shift);
            }

            if (bit_shift > 0 && (page + 1) < (OLED_HEIGHT / 8)) {
                int buf_index_next = (page + 1) * OLED_WIDTH + (current_x + col);
                oled_buffer[buf_index_next] |= (glyph_col >> (8 - bit_shift));
            }
        }

        current_x += 8;
        p += bytes_read;
    }
}

void displayRefresh(void) {
    uint8_t control_bytes[] = {
        0x00, 0x21, 0x00, OLED_WIDTH - 1,
        0x00, 0x22, 0x00, (OLED_HEIGHT / 8) - 1
    };
    i2c_master_transmit(dev_handle, control_bytes, sizeof(control_bytes), 1000);

    uint8_t payload[sizeof(oled_buffer) + 1];
    payload[0] = 0x40;
    memcpy(&payload[1], oled_buffer, sizeof(oled_buffer));
    
    i2c_master_transmit(dev_handle, payload, sizeof(payload), 1000);
}

void displayInitial(void){
    displayClear();
    displayDrawString(0,20,"Sistema G2");
    displayDrawString(0,30,"Seja bem-vindo");
    displayDrawString(0,40,"Aperte Enter");
    displayRefresh();
}

void displayBatterySelect(int raw){
    char buffer[32];
    snprintf(buffer, sizeof(buffer), "%d: %s", raw, batteries[raw].name);
    displayClear();
    displayDrawString(0,20,"Escolha bateria");
    displayDrawString(0,30,buffer);
    displayRefresh();
}

void displayFinalVoltageSelect(int raw, int batterySelected, float nowVoltage){
    char buffer[32];
    batteryData b = batteries[batterySelected];
    displayClear();
    displayDrawString(0,20,"Voltagem final");
    snprintf(buffer, sizeof(buffer), "%dV", raw);
    displayDrawString(0,30,buffer);

    float porcentage = (nowVoltage/b.maxVoltage)*100;
    snprintf(buffer, sizeof(buffer), "-A %.1fV %.0f%%", nowVoltage, porcentage);
    displayDrawString(0,50,buffer);
    displayRefresh();
}

void displayInOperation(int isCharging, int isDischarging, float initialVoltage, float finalVoltage, float nowVoltage, float nowCurrent, int batterySelected){
    float porcentage = 0.00;
    batteryData b = batteries[batterySelected];
    displayClear();

    char buffer[32];
    if(isCharging){
        displayDrawString(0,20,"CHARGING");
        porcentage = ((nowVoltage - initialVoltage)/(finalVoltage - initialVoltage))*100;
    }
    else if(isDischarging){
        displayDrawString(0,20,"DISCHARGING");
        porcentage = ((initialVoltage - nowVoltage)/(initialVoltage - finalVoltage))*100;
    }

    snprintf(buffer, sizeof(buffer), "%.1f%%", porcentage);
    displayDrawString(0,30,buffer);
    
    porcentage = (nowVoltage/b.maxVoltage)*100;
    snprintf(buffer, sizeof(buffer), "%.1fA %.1fV %.0f%%", nowCurrent, nowVoltage, porcentage);
    displayDrawString(0,50,buffer);
    displayRefresh();
}

void displayPreOperation(void){
    displayClear();
    displayDrawString(0,20,"Início em 5s");
    displayDrawString(0,30,"Cancele em Enter");
    displayRefresh();
}

void displayEmergency(void){
    displayClear();
    displayDrawString(0,20,"PARADO");
    displayDrawString(0,30,"ERRO");
    displayRefresh();
}